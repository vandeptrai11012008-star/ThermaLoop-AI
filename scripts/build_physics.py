#!/usr/bin/env python3
"""Check physical-model evidence identity and build its static browser bundle."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def digest(raw):return hashlib.sha256(raw).hexdigest()
def build(check=False):
    raw=(ROOT/"science/physics/results.json").read_bytes();data=json.loads(raw)
    for name,expected in data["sourceHashes"].items():
        file=(ROOT/name).resolve()
        if not file.is_relative_to(ROOT) or digest(file.read_bytes())!=expected:raise ValueError("Stale physical-model evidence: "+name)
    if data["protocol"]!=json.loads((ROOT/"physics/protocol.json").read_text()):raise ValueError("Physical protocol differs")
    if not all(v is True for v in data["gates"].values()):raise ValueError("Unmet physical-model verification gate")
    meta={"schemaVersion":1,"sha256":digest(raw),"bytes":len(raw)}
    js="/* Generated by scripts/build_physics.py; do not edit. */\n"
    for name,value in [("ThermaPhysicsData",data),("ThermaPhysicsBuild",meta)]:js+="globalThis."+name+" = "+json.dumps(value,separators=(",",":"),ensure_ascii=True)+";\n"
    file=ROOT/"science/physics-data.js"
    if check:
        if file.read_text()!=js:raise ValueError("Physical-model bundle is stale")
    else:file.write_text(js)
    print("Physical-model result SHA-256:",digest(raw))
if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--check",action="store_true");build(parser.parse_args().check)
