#!/usr/bin/env python3
"""Verify pinned reference snapshots and build the separate offline research registry."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "science/validation"


def build(check=False):
    raw = (DATA / "research.json").read_bytes()
    obj = json.loads(raw)
    for source in obj["provenance"]["snapshots"]:
        assert Path(source["file"]).name == source["file"], "Snapshot must be local"
        content = (DATA / source["file"]).read_bytes()
        assert hashlib.sha256(content).hexdigest() == source["sha256"], source["file"]
    anchor = obj["anchor"]
    text = (DATA / "villanova-upstream.yaml").read_text()
    # A fixed, hash-pinned YAML snapshot; reject a changed format rather than
    # guessing missing values. No downloaded Python source is executed.
    block = re.search(r"R_Fo_vs_flow:\n((?:    [\d.]+: [\d.]+\n)+)", text)[1]
    pairs = [(float(a), float(b)) for a, b in re.findall(r"([\d.]+): ([\d.]+)", block)]
    assert pairs == [(p["flow_L_min"], p["R_Tin_K_W"]) for p in anchor["points"]]
    for field, key in [("R_LMTD_KperW", "R_LMTD_K_W"), ("calibrate_at_LPM", "calibrationFlow_L_min")]:
        assert float(re.search(r"\b" + field + r":\s*([\d.]+)", text)[1]) == anchor[key]
    for key, val in anchor["geometry"].items():
        assert float(re.search(r"\b" + key + r":\s*([\deE.+-]+)", text)[1]) == val
    assert float(re.search(r"heat_load_W:\s*([\d.]+)",text)[1]) == anchor["conditions"]["power_W"]
    assert float(re.search(r"inlet_temp_C:\s*([\d.]+)",text)[1]) == anchor["conditions"]["Tin_C"]
    assert anchor["primarySourceVerified"] is False
    assert all(s["primaryDocumentSHA256"] is None for s in obj["sources"])
    metadata = {"schemaVersion":obj["schemaVersion"], "researchSHA256":hashlib.sha256(raw).hexdigest(), "researchBytes":len(raw)}
    bundle = ("/* Generated by scripts/build_validation.py; do not edit. */\n"
              + "globalThis.ThermaValidationData = " + json.dumps(obj,separators=(",",":"),ensure_ascii=True) + ";\n"
              + "globalThis.ThermaValidationBuild = " + json.dumps(metadata,separators=(",",":")) + ";\n")
    target = ROOT / "science/validation-data.js"
    if check:
        assert target.read_text() == bundle, "Research bundle is stale"
    else:
        target.write_text(bundle)
    print("Research registry SHA-256:",metadata["researchSHA256"])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    build(parser.parse_args().check)
