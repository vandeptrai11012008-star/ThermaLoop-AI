#!/usr/bin/env python3
"""Check result/source identity and build a browser bundle without SciPy."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
RESULT=ROOT/"science/numerical/results.json"


def build(check=False):
    raw=RESULT.read_bytes();data=json.loads(raw)
    if not data["gates"] or not all(value is True for value in data["gates"].values()):
        raise ValueError("Numerical protocol contains an unmet gate")
    for name,expected in data["sourceHashes"].items():
        file=(ROOT/name).resolve()
        if not file.is_relative_to(ROOT) or hashlib.sha256(file.read_bytes()).hexdigest()!=expected:
            raise ValueError("Stale numerical artifact: "+name)
    config=json.loads((ROOT/"research/verification-config.json").read_text())
    if data["protocol"]!=config:
        raise ValueError("Result protocol differs from the versioned configuration")
    meta={"schemaVersion":data["schemaVersion"],"sha256":hashlib.sha256(raw).hexdigest(),"bytes":len(raw),"scope":"Synthetic numerical verification only"}
    js=("/* Generated by scripts/build_numerical.py; do not edit. */\n"
        +"globalThis.ThermaNumericalData = "+json.dumps(data,separators=(",",":"),ensure_ascii=True)+";\n"
        +"globalThis.ThermaNumericalBuild = "+json.dumps(meta,separators=(",",":"))+";\n")
    target=ROOT/"science/numerical-data.js"
    if check:
        if target.read_text()!=js:
            raise ValueError("Numerical browser bundle is stale")
    else:
        target.write_text(js)
    print("Numerical result SHA-256:",meta["sha256"])


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    build(parser.parse_args().check)
