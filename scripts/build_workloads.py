#!/usr/bin/env python3
"""Verify workload source identity and bundle saved inputs/results for offline use."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sha(raw):
    return hashlib.sha256(raw).hexdigest()
def build(check=False):
    raw=(ROOT/"science/workloads/data.json").read_bytes();data=json.loads(raw)
    result_raw=(ROOT/"science/workloads/results.json").read_bytes();results=json.loads(result_raw)
    for name,expected in data["sourceHashes"].items():
        file=(ROOT/name).resolve()
        if not file.is_relative_to(ROOT) or sha(file.read_bytes())!=expected:
            raise ValueError("Stale workload input: "+name)
    if results["inputSHA256"]!=sha(raw) or results["engineSHA256"]!=sha((ROOT/"science/workload-model.js").read_bytes()):
        raise ValueError("Stale workload evaluation")
    if not all(value is True for value in results["defaultResult"]["checks"].values()):
        raise ValueError("Workload accounting failed")
    # Large per-job results are reproducible exports; the interactive UI recomputes
    # its selected case. Retain the compact sweep, not duplicate full trajectories.
    summary={k:v for k,v in results.items() if k!="defaultResult"}
    meta={"schemaVersion":1,"inputSHA256":sha(raw),"resultSHA256":sha(result_raw),"engineSHA256":results["engineSHA256"]}
    js="/* Generated by scripts/build_workloads.py; do not edit. */\n"
    for name,value in [("ThermaWorkloadData",data),("ThermaWorkloadSweep",summary),("ThermaWorkloadBuild",meta)]:
        js+="globalThis."+name+" = "+json.dumps(value,separators=(",",":"),ensure_ascii=True)+";\n"
    target=ROOT/"science/workload-data.js"
    if check:
        if target.read_text()!=js:raise ValueError("Workload browser bundle is stale")
    else:target.write_text(js)
    print("Workload input SHA-256:",sha(raw))
if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--check",action="store_true")
    build(parser.parse_args().check)
